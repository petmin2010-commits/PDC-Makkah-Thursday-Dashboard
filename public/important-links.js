function buildGroups(q=''){
  const needle=String(q||'').trim().toLowerCase();
  if(!needle)return CFG.groups;
  return CFG.groups.map(g=>{
    const own=[g.title,g.sub].join(' ').toLowerCase().includes(needle);
    const links=g.links.filter(x=>own||[x.title,x.desc].join(' ').toLowerCase().includes(needle));
    return links.length?{...g,links}:null;
  }).filter(Boolean);
}

function makeQrDataUrl(text){
  if(typeof QRCode!=='function')return '';
  const holder=document.createElement('div');
  holder.style.cssText='position:fixed;left:-9999px;top:-9999px;width:160px;height:160px;opacity:0;pointer-events:none';
  document.body.appendChild(holder);
  try{
    new QRCode(holder,{
      text:String(text||''),
      width:160,
      height:160,
      colorDark:'#172d44',
      colorLight:'#ffffff',
      correctLevel:QRCode.CorrectLevel.M
    });
    const canvas=holder.querySelector('canvas');
    const img=holder.querySelector('img');
    return canvas?.toDataURL('image/png')||img?.src||'';
  }catch(error){
    console.error('Important links QR generation failed:',error);
    return '';
  }finally{
    holder.remove();
  }
}

